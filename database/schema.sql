-- ============================================================================
-- Login Seguro · esquema PostgreSQL (subconjunto del sistema IAA)
-- ============================================================================
-- Extraído de database/iaa_schema_pg.sql, conservando SOLO las tablas que
-- necesita el flujo de autenticación:
--
--   usuario / persona / rol            → credenciales
--   usuario_rol / usuario_permiso      → roles y permisos de la cuenta
--   permiso / rol_permiso              → matriz de permisos
--   logeo                              → bitácora de sesiones (entrada/salida)
--   intentos_login                     → bloqueo progresivo
--   bitacora                           → auditoría de acciones
--   notificacion                       → avisos internos al usuario
--
-- Ejecutar con: psql -d login_demo -f database/schema.sql
-- El instalador (php database/instalar.php) aplica este mismo archivo.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Roles y permisos
-- ----------------------------------------------------------------------------
-- Los ids se conservan EXACTAMENTE como los espera el código legado
-- (1 funcionario, 3 moderador, 4 supervisor, 5 administrador, 6 medico,
--  7 particular; el 2 estuvo reservado y nunca se usó).
CREATE TABLE IF NOT EXISTS rol (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS permiso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS rol_permiso (
    id_rol     BIGINT NOT NULL REFERENCES rol (id) ON DELETE CASCADE,
    id_permiso BIGINT NOT NULL REFERENCES permiso (id) ON DELETE CASCADE,
    PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE IF NOT EXISTS usuario_permiso (
    id_usuario BIGINT NOT NULL,
    id_permiso BIGINT NOT NULL,
    PRIMARY KEY (id_usuario, id_permiso)
);

-- ----------------------------------------------------------------------------
-- 2. Personas y usuarios
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS persona (
    id_persona       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(150) NOT NULL,
    correo           VARCHAR(150),
    ci_usuario       VARCHAR(20),
    telefono         VARCHAR(20),
    fecha_nacimiento DATE,
    sexo             VARCHAR(20),
    nacionalidad     VARCHAR(30),
    apellidos        VARCHAR(150),
    nombres          VARCHAR(150),
    ocr_texto        TEXT,
    ocr_datos        TEXT,
    ocr_leido_at     TIMESTAMPTZ,
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Compatibilidad con bases ya creadas (instalador idempotente).
ALTER TABLE persona ADD COLUMN IF NOT EXISTS fecha_nacimiento DATE;
ALTER TABLE persona ADD COLUMN IF NOT EXISTS sexo VARCHAR(20);
ALTER TABLE persona ADD COLUMN IF NOT EXISTS nacionalidad VARCHAR(30);
ALTER TABLE persona ADD COLUMN IF NOT EXISTS apellidos VARCHAR(150);
ALTER TABLE persona ADD COLUMN IF NOT EXISTS nombres VARCHAR(150);
ALTER TABLE persona ADD COLUMN IF NOT EXISTS ocr_texto TEXT;
ALTER TABLE persona ADD COLUMN IF NOT EXISTS ocr_datos TEXT;
ALTER TABLE persona ADD COLUMN IF NOT EXISTS ocr_leido_at TIMESTAMPTZ;

COMMENT ON COLUMN persona.ci_usuario IS
    'Cédula con formato opcional (V-12345678). La búsqueda por login es por usuario.ci_usuario.';

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona          BIGINT NOT NULL REFERENCES persona (id_persona) ON DELETE CASCADE,
    ci_usuario          VARCHAR(100) NOT NULL,
    contrasena          VARCHAR(255) NOT NULL,
    password_changed_at TIMESTAMPTZ,
    id_rol              BIGINT NOT NULL REFERENCES rol (id) DEFAULT 1,
    estado              VARCHAR(20) DEFAULT 'activo',
    ultimo_acceso       TIMESTAMPTZ,
    evidencia_cedula    VARCHAR(255),
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_usuario_ci ON usuario (ci_usuario);
COMMENT ON COLUMN usuario.estado IS 'activo | pendiente | rechazado';
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS evidencia_cedula VARCHAR(255);

-- Roles múltiples por cuenta (migración de roles múltiples del sistema real).
CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    id_rol     BIGINT NOT NULL REFERENCES rol (id) ON DELETE CASCADE,
    PRIMARY KEY (id_usuario, id_rol)
);

-- ----------------------------------------------------------------------------
-- 3. Seguridad: sesiones, intentos y auditoría
-- ----------------------------------------------------------------------------
-- Sin FK a usuario a propósito: el registro de sesiones debe sobrevivir al
-- borrado del usuario (id_user se conserva como referencia histórica).
CREATE TABLE IF NOT EXISTS logeo (
    id_logeo          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user           BIGINT,
    ci_user           VARCHAR(20),
    nombre_user       VARCHAR(150),
    f_ing             TIMESTAMPTZ,
    f_sal             TIMESTAMPTZ,
    dir_ip            VARCHAR(45),
    agent_u           VARCHAR(200),
    token_sesion      VARCHAR(64),
    estado            VARCHAR(20) DEFAULT 'activo',
    tipo_evento       VARCHAR(50),
    detalle           TEXT,
    last_activity     TIMESTAMPTZ,
    cerrada_por_admin BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_logeo_usuario ON logeo (ci_user, f_ing DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_logeo_token ON logeo (token_sesion)
    WHERE token_sesion IS NOT NULL;

CREATE TABLE IF NOT EXISTS intentos_login (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci_user               VARCHAR(20) NOT NULL UNIQUE,
    intentos              INTEGER DEFAULT 0,
    bloqueo_hasta         TIMESTAMPTZ,
    razon                 VARCHAR(255) DEFAULT '',
    exitoso               BOOLEAN DEFAULT FALSE,
    ultimo_intento        TIMESTAMPTZ,
    bloqueos_consecutivos INTEGER NOT NULL DEFAULT 0
);

-- id_logeo sin FK a propósito: la bitácora es evidencia forense.
CREATE TABLE IF NOT EXISTS bitacora (
    id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario  BIGINT REFERENCES usuario (id_usuario) ON DELETE SET NULL,
    id_logeo    BIGINT,
    accion      VARCHAR(255),
    categoria   VARCHAR(40),
    detalle     TEXT,
    fecha       TIMESTAMPTZ DEFAULT now(),
    ip          VARCHAR(45),
    user_agent  TEXT
);

CREATE INDEX IF NOT EXISTS idx_bitacora_fecha ON bitacora (fecha DESC);

-- Trigger: la bitácora no se modifica ni se borra (evidencia forense).
CREATE OR REPLACE FUNCTION bitacora_inmutable()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'La bitácora es de solo inserción: % no permitido', TG_OP;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_bitacora_inmutable ON bitacora;

CREATE TRIGGER trg_bitacora_inmutable
BEFORE UPDATE OR DELETE ON bitacora
FOR EACH ROW EXECUTE FUNCTION bitacora_inmutable();

CREATE TABLE IF NOT EXISTS notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      BIGINT NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    titulo          VARCHAR(200),
    mensaje         TEXT,
    tipo            VARCHAR(50),
    leida           BOOLEAN DEFAULT FALSE,
    fecha_creacion  TIMESTAMPTZ DEFAULT now()
);

